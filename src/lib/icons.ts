export function resolveIcon(name: string | null | undefined): LucideIcon {
  if (name && name in ICONS) return ICONS[name];
  return Circle;
}

export function resolveIconOrNull(name: string | null | undefined): LucideIcon | null {
  return name && name in ICONS ? ICONS[name] : null;
}
